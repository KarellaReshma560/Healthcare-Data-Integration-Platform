
-- -- 1. Create patients staging table
IF OBJECT_ID(N'dbo.stg_patients', N'U') IS NULL
BEGIN
    CREATE TABLE dbo.stg_patients (
        Id NVARCHAR(36),
        BIRTHDATE DATE,
        DEATHDATE DATE,
        SSN NVARCHAR(20),
        DRIVERS NVARCHAR(50),
        PASSPORT NVARCHAR(50),
        PREFIX NVARCHAR(20),
        FIRST NVARCHAR(100),
        MIDDLE NVARCHAR(100),
        LAST NVARCHAR(100),
        SUFFIX NVARCHAR(20),
        MAIDEN NVARCHAR(100),
        MARITAL NVARCHAR(10),
        RACE NVARCHAR(100),
        ETHNICITY NVARCHAR(100),
        GENDER NVARCHAR(20),
        BIRTHPLACE NVARCHAR(200),
        ADDRESS NVARCHAR(200),
        CITY NVARCHAR(100),
        STATE NVARCHAR(100),
        COUNTY NVARCHAR(100),
        FIPS NVARCHAR(10),
        ZIP NVARCHAR(10),
        LAT DECIMAL(10, 6),
        LON DECIMAL(10, 6),
        HEALTHCARE_EXPENSES DECIMAL(18, 2),
        HEALTHCARE_COVERAGE DECIMAL(18, 2),
        INCOME DECIMAL(18, 2),

        -- Identifies the staging data load
        stg_load_log_key BIGINT NULL
    );
END;


-- 2. Create providers staging table
IF OBJECT_ID(N'dbo.stg_providers', N'U') IS NULL
BEGIN
    CREATE TABLE dbo.stg_providers (
        Id NVARCHAR(36),
        ORGANIZATION NVARCHAR(36),
        NAME NVARCHAR(200),
        GENDER NVARCHAR(20),
        SPECIALITY NVARCHAR(200),
        ADDRESS NVARCHAR(200),
        CITY NVARCHAR(100),
        STATE NVARCHAR(100),
        ZIP NVARCHAR(10),
        LAT DECIMAL(10, 6),
        LON DECIMAL(10, 6),
        ENCOUNTERS BIGINT,
        PROCEDURES BIGINT,
        NPI NVARCHAR(20),
        stg_load_log_key BIGINT NULL
    );
END;


-- 3. Create payers staging table
IF OBJECT_ID(N'dbo.stg_payers', N'U') IS NULL
BEGIN
    CREATE TABLE dbo.stg_payers (
        Id NVARCHAR(36),
        NAME NVARCHAR(200),
        OWNERSHIP NVARCHAR(100),
        ADDRESS NVARCHAR(200),
        CITY NVARCHAR(100),
        STATE_HEADQUARTERED NVARCHAR(100),
        ZIP NVARCHAR(10),
        PHONE NVARCHAR(30),
        AMOUNT_COVERED DECIMAL(18, 2),
        AMOUNT_UNCOVERED DECIMAL(18, 2),
        REVENUE DECIMAL(18, 2),
        COVERED_ENCOUNTERS BIGINT,
        UNCOVERED_ENCOUNTERS BIGINT,
        COVERED_MEDICATIONS BIGINT,
        UNCOVERED_MEDICATIONS BIGINT,
        COVERED_PROCEDURES BIGINT,
        UNCOVERED_PROCEDURES BIGINT,
        COVERED_IMMUNIZATIONS BIGINT,
        UNCOVERED_IMMUNIZATIONS BIGINT,
        UNIQUE_CUSTOMERS BIGINT,
        QOLS_AVG DECIMAL(10, 4),
        MEMBER_MONTHS BIGINT,
        stg_load_log_key BIGINT NULL
    );
END;


-- 4. Create encounters staging table
IF OBJECT_ID(N'dbo.stg_encounters', N'U') IS NULL
BEGIN
    CREATE TABLE dbo.stg_encounters (
        Id NVARCHAR(36),
        START DATETIME2,
        STOP DATETIME2,
        PATIENT NVARCHAR(36),
        ORGANIZATION NVARCHAR(36),
        PROVIDER NVARCHAR(36),
        PAYER NVARCHAR(36),
        ENCOUNTERCLASS NVARCHAR(100),
        CODE NVARCHAR(50),
        DESCRIPTION NVARCHAR(500),
        BASE_ENCOUNTER_COST DECIMAL(18, 2),
        TOTAL_CLAIM_COST DECIMAL(18, 2),
        PAYER_COVERAGE DECIMAL(18, 2),
        REASONCODE NVARCHAR(50),
        REASONDESCRIPTION NVARCHAR(500),
        stg_load_log_key BIGINT NULL
    );
END;


-- 5. Create claims staging table
IF OBJECT_ID(N'dbo.stg_claims', N'U') IS NULL
BEGIN
    CREATE TABLE dbo.stg_claims (
        Id NVARCHAR(36),
        PATIENTID NVARCHAR(36),
        PROVIDERID NVARCHAR(36),
        PRIMARYPATIENTINSURANCEID NVARCHAR(36),
        SECONDARYPATIENTINSURANCEID NVARCHAR(36),
        DEPARTMENTID NVARCHAR(36),
        PATIENTDEPARTMENTID NVARCHAR(36),
        DIAGNOSIS1 NVARCHAR(50),
        DIAGNOSIS2 NVARCHAR(50),
        DIAGNOSIS3 NVARCHAR(50),
        DIAGNOSIS4 NVARCHAR(50),
        DIAGNOSIS5 NVARCHAR(50),
        DIAGNOSIS6 NVARCHAR(50),
        DIAGNOSIS7 NVARCHAR(50),
        DIAGNOSIS8 NVARCHAR(50),
        REFERRINGPROVIDERID NVARCHAR(36),
        APPOINTMENTID NVARCHAR(36),
        CURRENTILLNESSDATE DATE,
        SERVICEDATE DATE,
        SUPERVISINGPROVIDERID NVARCHAR(36),
        STATUS1 NVARCHAR(50),
        STATUS2 NVARCHAR(50),
        STATUSP NVARCHAR(50),
        OUTSTANDING1 DECIMAL(18, 2),
        OUTSTANDING2 DECIMAL(18, 2),
        OUTSTANDINGP DECIMAL(18, 2),
        LASTBILLEDDATE1 DATE,
        LASTBILLEDDATE2 DATE,
        LASTBILLEDDATEP DATE,
        HEALTHCARECLAIMTYPEID1 NVARCHAR(50),
        HEALTHCARECLAIMTYPEID2 NVARCHAR(50),
        stg_load_log_key BIGINT NULL
    );
END;